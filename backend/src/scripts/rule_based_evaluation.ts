
import fs from 'fs';
import path from 'path';
import readline from 'readline';
import { EnhancedRuleClassifier } from '../services/transactions/classification/EnhancedRuleClassifier';
import { UniversalAmountExtractor } from '../services/transactions/extraction/UniversalAmountExtractor';
import { CleanEmail } from '../types/transaction.types';

// Configuration
const DUMP_FILE_PATH = path.join(__dirname, 'emails_dump.json');
const OUTPUT_DIR = __dirname;
const BATCH_SIZE = 1000;

// Output filenames
const FILE_STATS = 'email_processing_stats.json';
const FILE_TRANSACTIONAL = 'transactional_emails.json';
const FILE_NON_TRANSACTIONAL = 'non_transactional_emails.json';
const FILE_OTHER = 'other_emails.json'; // Unclassified or difficult to categorize

// Stats Interface
interface ProcessStats {
    totalProcessed: number;
    successfullyParsed: number;
    transactionalCount: number;
    nonTransactionalCount: number;
    otherCount: number;
    failures: number;
    skipped: number;
}

// Main Execution
async function main() {
    console.log('---------------------------------------------------------');
    console.log('Starting Rule-Based Email Evaluation');
    console.log(`Input File: ${DUMP_FILE_PATH}`);
    console.log('---------------------------------------------------------');

    if (!fs.existsSync(DUMP_FILE_PATH)) {
        console.error(`Error: File not found at ${DUMP_FILE_PATH}`);
        process.exit(1);
    }

    const stats: ProcessStats = {
        totalProcessed: 0,
        successfullyParsed: 0,
        transactionalCount: 0,
        nonTransactionalCount: 0,
        otherCount: 0,
        failures: 0,
        skipped: 0
    };

    // Arrays to hold results (Writing fully to memory might be risky for 25k large objects, 
    // but requested to be "saved locally" at end. We will store minimal necessary data or full objects if memory permits.
    // 25k emails is ~50MB-100MB roughly, should be fine in Node heap.)
    const transactionalEmails: any[] = [];
    const nonTransactionalEmails: any[] = [];
    const otherEmails: any[] = [];

    const fileStream = fs.createReadStream(DUMP_FILE_PATH, { encoding: 'utf8' });
    const rl = readline.createInterface({
        input: fileStream,
        crlfDelay: Infinity
    });

    let currentLines: string[] = [];
    let isReadingObject = false;

    // We need to parse a JSON dump that might be an array or line-delimited objects or a huge formatted JSON file.
    // Based on previous conversations/context, it seems to be a standard JSON array or formatted JSON.
    // A safe way for a large file of objects is to assume it might be a JSON array `[ ... ]` formatted with indentation.
    // Simple state machine to read object by object.

    // BUT specific reading logic depends on format. 
    // If it's `emails_dump.json` generated by `fetch_label_emails.ts` using `JSON.stringify(allEmails, null, 2)`, 
    // it is a valid JSON array. Streaming parse is safer.
    // However, a simple balanced-brace parser works well for array elements.

    let braceDepth = 0;
    let objectBuffer = '';
    let inString = false;
    let escaped = false;

    console.log('Processing emails...');

    // Initialize Classifier
    // No explicit initialization needed for static class

    for await (const line of rl) {
        const trimmed = line.trim();

        // Skip Start/End of array
        if (stats.totalProcessed === 0 && trimmed === '[') continue;
        if (trimmed === ']') continue;

        // Naive JSON object extraction for list of objects
        // Assuming standard pretty print: starts with { ends with }, or },

        // Accumulate lines
        objectBuffer += line + '\n';

        for (let i = 0; i < line.length; i++) {
            const char = line[i];

            if (escaped) {
                escaped = false;
                continue;
            }

            if (char === '\\') {
                escaped = true;
                continue;
            }

            if (char === '"') {
                inString = !inString;
                continue;
            }

            if (!inString) {
                if (char === '{') {
                    braceDepth++;
                } else if (char === '}') {
                    braceDepth--;

                    if (braceDepth === 0) {
                        // End of object
                        let jsonStr = objectBuffer.trim();
                        // Remove trailing comma if exists (usually for items in array)
                        if (jsonStr.endsWith(',')) {
                            jsonStr = jsonStr.slice(0, -1);
                        }

                        try {
                            const emailRaw = JSON.parse(jsonStr);
                            processEmail(emailRaw, stats, transactionalEmails, nonTransactionalEmails, otherEmails);
                        } catch (e) {
                            // console.error('Failed to parse JSON object chunk', e);
                            stats.failures++;
                        }

                        // Reset buffer
                        objectBuffer = '';
                    }
                }
            }
        }

        if (stats.totalProcessed > 0 && stats.totalProcessed % 1000 === 0) {
            process.stdout.write(`\rProcessed: ${stats.totalProcessed} | Txn: ${stats.transactionalCount} | Non-Txn: ${stats.nonTransactionalCount}`);
        }
    }

    console.log('\n---------------------------------------------------------');
    console.log('Processing Complete.');
    console.log('Saving Output Files...');

    // Save outputs
    saveJson(FILE_STATS, stats);
    // For large arrays, saving might need streaming if too huge, but writeFileSync handles substantial strings.
    saveJson(FILE_TRANSACTIONAL, transactionalEmails);
    saveJson(FILE_NON_TRANSACTIONAL, nonTransactionalEmails);
    saveJson(FILE_OTHER, otherEmails);

    console.log('---------------------------------------------------------');
    console.log('Final Statistics:');
    console.log(JSON.stringify(stats, null, 2));
    console.log('---------------------------------------------------------');
}

function processEmail(rawEmail: any, stats: ProcessStats, txnList: any[], nonTxnList: any[], otherList: any[]) {
    stats.totalProcessed++;

    try {
        // Basic Validation
        if (!rawEmail || !rawEmail.id || !rawEmail.bodyText) {
            stats.failures++;
            return;
        }

        // 1. Construct CleanEmail object expected by Classifier
        const cleanEmail: CleanEmail = {
            id: rawEmail.id,
            subject: rawEmail.subject || '',
            cleanedBody: rawEmail.bodyText || '', // Using bodyText as cleanedBody for now
            from: rawEmail.from || '',
            internalDate: rawEmail.internalDate ? parseInt(rawEmail.internalDate) : Date.now(),
            hasAttachments: false // Metadata not always available in simple dump
        };

        // 2. Classify
        const classification = EnhancedRuleClassifier.classify(cleanEmail);

        if (!classification) {
            // Null means unclassified / unknown -> "Other"
            stats.otherCount++;
            otherList.push({
                email_id: cleanEmail.id,
                subject: cleanEmail.subject,
                from: cleanEmail.from,
                classification: 'unclassified'
            });
            return;
        }

        stats.successfullyParsed++;

        // 3. Categorize
        // Transaction TYPES: 'cc_spend', 'bank_debit', 'bank_credit', 'upi_debit', 'upi_credit', etc.
        // Non-Transaction TYPES: 'non_financial', 'bill_due' (sometimes considers txn?), 'statement'

        // We defined 'non_financial' explicitly in Classifier
        if (classification.type === 'non_financial') {
            stats.nonTransactionalCount++;
            nonTxnList.push({
                email_id: cleanEmail.id,
                subject: cleanEmail.subject,
                classification: classification
            });
        } else if (classification.type === 'unclassified') {
            stats.otherCount++;
            otherList.push({
                email_id: cleanEmail.id,
                subject: cleanEmail.subject,
                classification: classification
            });
        } else {
            // It is a Transaction
            stats.transactionalCount++;

            // 4. Extract Amount (Pure logic only)
            let extractedAmount = null;
            try {
                // Combine subject + body for extraction context same as used in Extractor classes
                const fullText = `${cleanEmail.subject} ${cleanEmail.cleanedBody}`;
                extractedAmount = UniversalAmountExtractor.extract(fullText);
            } catch (e) {
                // Extraction failed, which is expected for some tricky formats
                extractedAmount = null;
            }

            txnList.push({
                email_id: cleanEmail.id,
                subject: cleanEmail.subject,
                classification: classification,
                extracted_amount: extractedAmount
            });
        }

    } catch (e) {
        stats.failures++;
        // console.error(`Error processing email ${rawEmail?.id}:`, e);
    }
}

function saveJson(filename: string, data: any) {
    const fullPath = path.join(OUTPUT_DIR, filename);
    try {
        fs.writeFileSync(fullPath, JSON.stringify(data, null, 2));
        console.log(`Saved: ${filename}`); // (${(fs.statSync(fullPath).size / 1024 / 1024).toFixed(2)} MB)`);
    } catch (e) {
        console.error(`Error saving ${filename}:`, e);
    }
}

main().catch(console.error);
